<?php
/**
 * Настройки отправки писем.
 *
 * Честно: без заполнения этого файла письма могут не доходить.
 * Рекомендуемый режим — 'smtp' с ящиком на вашем домене.
 * Режим 'mail' работает только если хостинг настроил функцию mail()
 * и почта с вашего домена проходит SPF/DKIM-проверки.
 *
 * Пароли не храните в публичном репозитории: см. config/secrets.sample.php.
 */

$secrets = [];
if (is_file(__DIR__ . '/secrets.php')) {
    $secrets = require __DIR__ . '/secrets.php';
}

return [

    // 'smtp' | 'mail' | 'log' (log — ничего не отправляет, только пишет в storage/logs)
    'transport' => 'log',

    'smtp' => [
        'host'       => $secrets['smtp_host'] ?? '',
        'port'       => $secrets['smtp_port'] ?? 465,
        // 'ssl' (обычно порт 465) | 'tls' (обычно 587) | 'none'
        'encryption' => $secrets['smtp_encryption'] ?? 'ssl',
        'username'   => $secrets['smtp_username'] ?? '',
        'password'   => $secrets['smtp_password'] ?? '',
        'timeout'    => 15,
        // Проверять сертификат сервера. Отключайте только при явной проблеме хостинга.
        'verify_peer'=> true,
    ],

    // От кого уходят письма. Адрес должен быть на вашем домене,
    // иначе письма попадут в спам.
    'from' => [
        'email' => 'no-reply@example-potolki.ru',
        'name'  => 'КОНТУР — натяжные потолки',
    ],

    // Куда приходят заявки. Можно указать несколько адресов.
    'to' => [
        'info@example-potolki.ru',
    ],

    // Копия заявок (например, руководителю). Пустой массив — не отправлять.
    'bcc' => [],

    // Отправлять ли клиенту письмо-подтверждение (только если он указал email).
    'client_copy' => true,

    'subjects' => [
        'owner'  => 'Заявка № {id} — {form}',
        'client' => 'Ваш расчёт и заявка № {id}',
    ],

    // ── Очередь ───────────────────────────────────────────────────────────
    // Если почта временно недоступна, письмо сохраняется в storage/mail-queue
    // и отправляется повторно командой из README_DEPLOY.md.
    'queue' => [
        'enabled'      => true,
        'max_attempts' => 5,
    ],

    // Максимальный размер одного письма, байт (защита от раздувания заявок).
    'max_body_bytes' => 262144,
];

# Разделитель, допускающий вводные слова и запятые между глаголом и предметом:
# «выставите, пожалуйста, счёт», «пришлите нам, пожалуйста, реквизиты»
SEP = r"[\s,]+(?:\w+[\s,]+){0,2}"

# Глаголы и обороты, указывающие, что клиент именно ПРОСИТ, а не упоминает
REQUEST_VERBS = re.compile(
    r"(пришлите|пришлете|пришлёте|направьте|вышлите|отправьте|предоставьте|приложите|"
    r"сообщите|укажите|подскажите|уточните|дайте|нужен|нужна|нужно|нужны|требуется|"
    r"требуются|интересует|интересуют|прошу|просим|хотел[аи]?\s+бы|можете\s+ли|"
    r"есть\s+ли|запрашива\w+|поделитесь|скинь|подготовьте|оформите|выставите|выставьте)",
    re.IGNORECASE,
)

# Отрицания: «реквизиты не нужны», «счёт не требуется»
NEGATION = re.compile(
    r"(не\s+нужн\w*|не\s+требу\w*|не\s+надо|без\s+|не\s+высылайте|не\s+присылайте|"
    r"уже\s+ест[ьи]|уже\s+получил\w*|не\s+обязательн\w*)",
    re.IGNORECASE,
)


@dataclass
class RequestPattern:
    request_type: str
    description: str
    patterns: list[str]
    weight: float = 1.0
    require_verb: bool = False
    compiled: list[re.Pattern] = field(default_factory=list)

    def __post_init__(self) -> None:
        self.compiled = [re.compile(p, re.IGNORECASE | re.UNICODE) for p in self.patterns]

    def search(self, text: str) -> str | None:
        for pattern in self.compiled:
            for match in pattern.finditer(text):
                window = text[max(0, match.start() - 90): match.end() + 60]
                if NEGATION.search(window):
                    continue
                if self.require_verb and not REQUEST_VERBS.search(window):
                    continue
                return match.group(0)
        return None



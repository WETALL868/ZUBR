def is_vague(text: str) -> bool:
    return any(p.search(text) for p in _VAGUE_RE)


def find_quote(text: str, match_text: str, width: int = 160) -> str:
    """Короткая цитата вокруг найденного совпадения."""
    if not text or not match_text:
        return ""
    idx = text.lower().find(match_text.lower())
    if idx < 0:
        return match_text[:width]
    start = max(0, idx - 60)
    end = min(len(text), idx + len(match_text) + 100)
    quote = text[start:end].strip().replace("\n", " ")
    quote = re.sub(r"\s{2,}", " ", quote)
    if start > 0:
        quote = "…" + quote
    if end < len(text):
        quote = quote + "…"
    return quote[: width + 40]


def manager_requests_from_client(text: str) -> list[str]:
    """Что менеджер запросил у клиента (основание для WAITING_FOR_CLIENT)."""
    reasons = []
    for pattern, reason in _MANAGER_ASKS_COMPILED:
        if pattern.search(text or ""):
            reasons.append(reason)
    return reasons

/**
 * Открытие главной страницы по адресу с якорем — например «/#order»,
 * куда ведёт кнопка «Оформить заказ» со страниц товаров.
 *
 * Исправляет две вещи, из-за которых покупатель попадал не туда, куда вёл
 * адрес. Обе видны только на главной: она единственная подгружает styles.css
 * асинхронно — в документ встроен критический CSS, остальное приезжает
 * следом.
 *
 * 1. Промах мимо формы.
 *    Браузер видит в документе элемент id="order" и сразу прокручивает
 *    страницу к нему. В этот момент применён только критический CSS, и всё,
 *    что выше формы, занимает заметно больше места. Приезжает styles.css,
 *    разметка сжимается на две-пять тысяч пикселей — а к якорю браузер
 *    больше не возвращается. Покупатель оказывался ниже формы заказа, у
 *    самого низа страницы.
 *    Лечится повторной прокруткой к якорю после того, как стили применились.
 *
 * 2. Страница «уезжает вниз» на глазах.
 *    В стилях задано scroll-behavior: smooth — это нужно для плавных
 *    переходов по ссылкам внутри страницы. Но то же правило действует и на
 *    самый первый переход к якорю при загрузке, и вместо готовой страницы
 *    человек видит, как она несколько тысяч пикселей едет вниз сама.
 *    Лечится тем, что на время загрузки плавность отключается: место
 *    назначения то же самое, просто страница открывается сразу на нём.
 *
 * Что важно и почему сделано именно так:
 *   • оба обхода включаются, только если в адресе есть якорь; обычная
 *     загрузка главной не затрагивается вовсе;
 *   • плавность снимается стилем самого элемента <html> — так надёжнее
 *     всего, потому что styles.css приезжает позже и правило из файла
 *     иначе перекрыло бы наше;
 *   • плавность возвращается сразу после наведения на якорь, поэтому
 *     ссылки внутри страницы работают как раньше;
 *   • если человек уже сам тронул страницу (колесо, палец, клавиша), мы
 *     к якорю не возвращаемся: перебивать чужую прокрутку хуже, чем
 *     неточный якорь;
 *   • два кадра ожидания: смена rel на "stylesheet" применяет стили не
 *     мгновенно, и без паузы мы измерили бы ещё старую разметку.
 */
(function () {
  "use strict";

  var target = location.hash.length > 1 ? location.hash.slice(1) : "";
  if (!target) {
    return;
  }

  var root = document.documentElement;
  var hadOwnValue = root.style.scrollBehavior;
  root.style.scrollBehavior = "auto";

  var restoreSmooth = function () {
    root.style.scrollBehavior = hadOwnValue;
  };

  var userMoved = false;
  var noticeMove = function () {
    userMoved = true;
    restoreSmooth();
  };
  ["wheel", "touchstart", "keydown", "mousedown"].forEach(function (name) {
    window.addEventListener(name, noticeMove, { passive: true, once: true });
  });

  // Подстраховка: если styles.css уже лежит в кеше браузера или почему-то
  // не сообщит о загрузке, плавность всё равно вернётся.
  window.addEventListener("load", function () {
    window.setTimeout(restoreSmooth, 0);
  });

  window.compUterAnchorAfterCss = function () {
    if (userMoved) {
      return;
    }

    window.requestAnimationFrame(function () {
      window.requestAnimationFrame(function () {
        if (userMoved) {
          return;
        }

        var element = document.getElementById(target);
        if (element) {
          element.scrollIntoView({ block: "start", behavior: "instant" });
        }

        restoreSmooth();
      });
    });
  };
})();
